-- 0008_fs_jobs_resumed: 标记"这条任务是重试来的"（设计 712 行 一键重试）。
--
-- 为什么是一列而不是重试时透传一个函数参数：跨盘移动是"复制 → 校验 → 删源"
-- 三步，中断点可能落在"副本已校验通过、源还没删"上 —— 那时源和目标各有一
-- 份内容相同的文件。重跑时必须认出这个状态并只补上"删源"；而认出它的依据
-- 若是内存里的一个参数，面板在重跑途中再崩一次，重启后这条任务就变回"全新
-- 的移动"，撞上自己上次留下的副本（"目标已存在"），于是**永远**无法完成。
-- 一个卡死在"重试也失败"的任务比没有重试按钮更糟：用户已经点过那个按钮了。
--
-- 反过来，全新一次提交的移动撞见同名目标必须照旧报错（409）：那时目标可能
-- 是用户自己的文件，悄悄把源删掉等于吃掉他的东西。所以这个标志必须区分得
-- 开两种情形，而"是不是重试"正是那个区分点。
ALTER TABLE fs_jobs ADD COLUMN resumed INTEGER NOT NULL DEFAULT 0;
