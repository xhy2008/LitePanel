-- 0007_fs_jobs_permanent: 删除任务的一个布尔必须能活过重启（M6-T4 第二阶段）。
--
-- permanent=1 的 delete 直接永久删除、不进回收站（盘根写不进回收站时用户
-- 的唯一出路，界面上已经二次确认）。它和 cancel_requested 是同一类字段：
-- 都是"用户已经做过的、不可从盘上重新推断出来的决定"。
--
-- 为什么必须落库而不是塞进执行器的函数参数：任务此刻可能还在排队。用户对
-- 一条排队中的永久删除点了提交，面板随即崩掉/升级——标志不落盘的话，重启
-- 后队列只能按默认分支处理，把它当成"进回收站"执行。那个结果两边都不对：
-- 用户明确选了"不可撤销地删除"（比如那是一段含密钥的日志，他要的是真的没了），
-- 重启却偷偷给他留了一份可还原的副本在盘上。反过来把默认删除误判成永久
-- 删除更是直接吃掉"还原"这个唯一的后悔药。两个方向都得防，所以它得在库里。
--
-- 用 ALTER 而不是改 0006：迁移按版本号判定是否已应用，改 0006 对已经跑过
-- 它的库不会再执行——老库里会永远缺这一列。这与 0005 给 term_sessions 补
-- exit_status 是同一个做法。
ALTER TABLE fs_jobs ADD COLUMN permanent INTEGER NOT NULL DEFAULT 0;
